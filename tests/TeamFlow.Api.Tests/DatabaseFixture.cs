using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Npgsql;
using TeamFlow.Api.Data;
using TeamFlow.Api.Features.Executions;
using Xunit;

namespace TeamFlow.Api.Tests;

public sealed class DatabaseFixture : IAsyncLifetime
{
    private readonly string _databaseName = "teamflow_test_" + Guid.NewGuid().ToString("N");
    private string _adminConnection = "";
    private string _testConnection = "";
    public TestClock Clock { get; } = new();
    public WebApplicationFactory<Program> Factory { get; private set; } = new();

    public async Task InitializeAsync()
    {
        var configuredConnection = Environment.GetEnvironmentVariable("ConnectionStrings__Database")
            ?? throw new InvalidOperationException("Configure the local PostgreSQL connection before integration tests.");
        _adminConnection = new NpgsqlConnectionStringBuilder(configuredConnection) { Timeout = 30, CommandTimeout = 30 }.ConnectionString;
        await using var connection = new NpgsqlConnection(_adminConnection);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand($"CREATE DATABASE {_databaseName}", connection);
        await command.ExecuteNonQueryAsync();
        var settings = new NpgsqlConnectionStringBuilder(_adminConnection) { Database = _databaseName };
        _testConnection = settings.ConnectionString;
        Factory = CreateFactory();
        using var scope = Factory.Services.CreateScope();
        await scope.ServiceProvider.GetRequiredService<AppDbContext>().Database.MigrateAsync();
    }

    private WebApplicationFactory<Program> CreateFactory() => new WebApplicationFactory<Program>().WithWebHostBuilder(builder => builder
            .UseEnvironment("Testing")
            .UseSetting("ConnectionStrings:Database", _testConnection)
            .UseSetting("Server:Url", "http://localhost:5080")
            .ConfigureServices(services => services.AddSingleton<TimeProvider>(Clock)));

    public async Task RestartAsync()
    {
        await Factory.DisposeAsync();
        Factory = CreateFactory();
    }

    public async Task<T> WithSchedulerAsync<T>(Func<ExecutionScheduler, Task<T>> action)
    {
        using var scope = Factory.Services.CreateScope();
        return await action(scope.ServiceProvider.GetRequiredService<ExecutionScheduler>());
    }

    public async Task DisposeAsync()
    {
        await Factory.DisposeAsync();
        if (string.IsNullOrEmpty(_adminConnection)) return;
        await using var connection = new NpgsqlConnection(_adminConnection);
        await connection.OpenAsync();
        // The name is generated by this fixture; never drop the configured application database.
        await using var command = new NpgsqlCommand($"DROP DATABASE IF EXISTS {_databaseName} WITH (FORCE)", connection);
        await command.ExecuteNonQueryAsync();
    }
}

public sealed class TestClock : TimeProvider
{
    private long _ticks = DateTimeOffset.UtcNow.Ticks;
    public override DateTimeOffset GetUtcNow() => new(Interlocked.Read(ref _ticks), TimeSpan.Zero);
    public void Advance(TimeSpan duration) => Interlocked.Add(ref _ticks, duration.Ticks);
}
